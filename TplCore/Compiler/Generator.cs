        #region Declaration

        private static string OpenBlockNamePrefix = "<!--";
        private static string BlockNameSuffix = "-->";
        private static string CloseBlockNamePrefix = "<!--/";

        private static string TagPrefix = "{";
        private static string TagSuffix = "}";
        private static string StaticStringPrefix = "static:";
        private static string LoadStringPrefix = "load:";
        private static string DefaultValueIndicator = ":";


        /*  In tag name
         *  Use exactly static naming for auto-located value
         *  Ex: {static:Resources.Lang.lblUserName} will be compiled to Resources.Lang.lblUserName in template object
         */

        public readonly string TemplateName;
        private int StringCounter = 0;
        private int TagCounter = 0;
        private int cz = 1000;

        private static string BlockVariablePrefix = "";
        private static string TagVariablePrefix = "t";
        private static string StringVariablePrefix = "s";

        // Use 2 hashtable to resolve duplicated block name
        private static Hashtable BlockNames = null;
        private static Hashtable BlockVariables = null;

        private string NamespaceName;
        private string ProjectName;
        private bool IsRootNS = false;
        private string TemplateUrl;

        private bool IsWebSite = true;

        #endregion

        public Generator(string templateName, string projectName)
            : this(templateName, projectName, true)
        {

        }

        public Generator(string templateName, string projectName, bool isWebSite)
        {
            IsWebSite = isWebSite;

            // Relative url to template file
            TemplateUrl = UrlLocater.JumpOut(templateName.Replace(TplSettings.Dot, TplSettings.UrlSlash) + TplSettings.UrlSlash, 1);

            ProjectName = ToNamespaceName(projectName);
            int i = templateName.LastIndexOf(TplSettings.Dot);
            IsRootNS = -1 == i;
            if (!IsRootNS)
            {
                NamespaceName = templateName.Substring(0, i);
                //// Remove starting seperator
                //if (NamespaceName.StartsWith(TplSettings.Seperator))
                //{
                //    NamespaceName = NamespaceName.Remove(0, TplSettings.Seperator.Length);
                //}

                TemplateName = templateName.Substring(i + 1);
            }
            else
            {
                TemplateName = templateName;
            }

            BlockNames = new Hashtable();
            BlockVariables = new Hashtable();
        }

        #region Header and Footer

        private string OpenTemplate()
        {
            return "\t\tpublic class " + TemplateName + TplSettings.TemplateSuffix + " : Template\r\n\t\t{\r\n";
        }

        private string OpenTemplate_NS()
        {
            StringBuilder builder = new StringBuilder(200);
            builder.Append("// <auto-generated />\r\n");
            builder.Append("#region!!!This file is auto-generated by TplBuilder, don't modify it manually!!!\r\n");
            builder.Append("using System;\r\nusing System.Web;\r\nusing System.Text;\r\nusing TplCore;\r\nusing TplCore.Element;\r\n");
            builder.Append("#pragma warning disable\r\n");

            if (IsWebSite)
            {
                builder.Append("namespace " + TplSettings.CompanyName + "." + ProjectName + "." + TplSettings.PresentationLayer + "\r\n{\r\n\t");
            }
            else
            {
                builder.Append("namespace " + ProjectName.Replace('_', '.') + "\r\n{\r\n\t");
            }


            if (!IsRootNS)
            {
                builder.Append("using " + NamespaceName + ";\r\n\tnamespace " + NamespaceName + "\r\n\t{\r\n");
            }
            else
            {
                builder.Append("//{\r\n");
            }

            return builder.ToString();
        }

        private string CloseTemplate()
        {
            return "\r\n\t\t}\r\n\r\n";
        }

        private string CloseTemplate_NS()
        {
            if (!IsRootNS)
            {
                return "\t}\r\n}\r\n#pragma warning enable\r\n#endregion";
            }
            else
            {
                return "\t//}\r\n}\r\n#pragma warning enable\r\n#endregion";
            }
        }

        private string OpenBlock(string name)
        {
            if (BlockNames.ContainsKey(name))
            {
                int i = (int)(BlockNames[name]) + 1;
                BlockNames[name] = i;
                return "\t\tpublic class " + name + i + TplSettings.BlocSuffix + ": Block\r\n\t\t{\r\n";
            }
            else
            {
                BlockNames.Add(name, 0);
                return "\t\tpublic class " + name + TplSettings.BlocSuffix + ": Block\r\n\t\t{\r\n";
            }
        }

        private string OpenBlock(string name, string parentName)
        {
            if (BlockNames.ContainsKey(name))
            {
                int i = (int)(BlockNames[name]) + 1;
                BlockNames[name] = i;
                return "\t\tpublic class " + parentName + TplSettings.Seperator + name + i + TplSettings.BlocSuffix + ": Block\r\n\t\t{\r\n";
            }
            else
            {
                BlockNames.Add(name, 0);
                return "\t\tpublic class " + parentName + TplSettings.Seperator + name + TplSettings.BlocSuffix + ": Block\r\n\t\t{\r\n";
            }
        }

        private string CloseBlock()
        {
            return "\t\t}\r\n\r\n";
        }

        #endregion

        #region Searching

        /// <summary>
        /// Split text to List of NonBlockChunk and BlockChunk objects
        /// </summary>
        /// <param name="text"></param>
        /// <returns></returns>
        private List<object> SplitBlock(string text) // First level only
        {
            if (String.IsNullOrEmpty(text)) return null;
            List<object> objs = new List<object>();

            // Open Block
            int i1 = text.IndexOf(OpenBlockNamePrefix);
            if (-1 == i1)
            {
                objs.Add(new NonBlockChunk(text));
                return objs;
            }

            int i2 = text.IndexOf(BlockNameSuffix, i1);
            if (-1 == i2)
            {
                objs.Add(new NonBlockChunk(text));
                return objs;
            }

            int start = i1 + OpenBlockNamePrefix.Length;
            int length = i2 - start;

            string name = text.Substring(start, length);

            // Close Block
            int j1 = text.IndexOf(CloseBlockNamePrefix + name + BlockNameSuffix, i2);
            if (-1 == j1)
            {
                objs.Add(new NonBlockChunk(text));
                return objs;
            }

            // Check Block name is valid
            if (IsBlockName(name))
            {
                start = i1 + OpenBlockNamePrefix.Length + name.Length + BlockNameSuffix.Length;
                length = j1 - start;

                string beginner = text.Substring(0, i1);
                objs.Add(new NonBlockChunk(beginner));

                name = ToPropertyName(name);
                string content = text.Substring(start, length);
                objs.Add(new BlockChunk(name, content));

                string ender = text.Substring(j1 + CloseBlockNamePrefix.Length + name.Length + BlockNameSuffix.Length);
                List<object> objs1 = SplitBlock(ender);

                if (null != objs1) objs.AddRange(objs1);
            }
            else
            {
                objs.Add(new NonBlockChunk(text));
            }

            return objs;
        }

        /// <summary>
        /// Find first tag, return tag name, start content, end content
        /// </summary>
        /// <param name="text"></param>
        /// <returns></returns>
        private object[] FindFirstTag(string text)
        {
            return FindFirstTag(text, 0);
        }

        /// <summary>
        /// Find first tag, return tag name, start content, end content.
        /// </summary>
        /// <param name="text"></param>
        /// <param name="index"></param>
        /// <returns></returns>
        private object[] FindFirstTag(string text, int index)
        {
            if (String.IsNullOrEmpty(text)) return null;

            int i1 = text.IndexOf(TagPrefix, index);
            if (-1 == i1) return null;

            int i2 = text.IndexOf(TagSuffix, i1 + TagPrefix.Length);
            if (-1 == i2) return null;

            int start = i1 + TagPrefix.Length;
            int length = i2 - start;

            string name = text.Substring(start, length);

            if (IsTagName(name))
            {
                string beginner = text.Substring(0, i1);
                string ender = text.Substring(i1 + TagPrefix.Length + name.Length + TagSuffix.Length);

                return new object[] { beginner, name, ender };
            }
            else
            {
                return FindFirstTag(text, i1 + 1);
            }
        }

        #endregion

        /// <summary>
        /// Render a text to a class.
        /// </summary>
        /// <param name="text">Input text</param>
        /// <returns></returns>
        public string RenderTemplate(string text)
        {
            if (String.IsNullOrEmpty(text)) return null;

            Filtering.FilterTemplate(ref text, TemplateUrl);

            List<string> LTag = new List<string>();
            StringBuilder builder = new StringBuilder(cz);

            builder.Append(OpenTemplate_NS());
            builder.Append(RenderBlock(text, TemplateName, ref LTag));
            builder.Append(CloseTemplate_NS());

            return builder.ToString();
        }



        #region Render Block

        /// <summary>
        /// Render block content with provided parent block name.
        /// </summary>
        /// <param name="text">Input text</param>
        /// <param name="parentName">Parent block name</param>
        /// <param name="LTag">Store all tag names for render ToString method</param>
        /// <returns></returns>
        private string RenderBlock(string text, string parentName, ref List<string> LTag)
        {
            List<object> objs = SplitBlock(text);
            StringBuilder builder = new StringBuilder(cz);
            if (null == objs)
            {
                builder.Append(OpenBlock(parentName));
                builder.Append(RenderToStringMethod(ref LTag, null, null, (parentName == TemplateName)));
                builder.Append(CloseBlock());
                return builder.ToString();
            }
            int c = objs.Count;

            // Open
            if (parentName == TemplateName)
            {
                builder.Append(OpenTemplate());
            }
            else
            {
                builder.Append(OpenBlock(parentName));
            }

            List<string> fields = new List<string>();
            List<bool?> isObjects = new List<bool?>();

            bool bHasChildBlock = false;
            List<int> ChildBlockIdxs = new List<int>();
            for (int i = 0; i < c; i++)
            {
                object obj = objs[i];
                if (obj.GetType() == typeof(NonBlockChunk))
                {
                    // Append String and tag
                    builder.Append(RenderNonBlock(((NonBlockChunk)(obj)).Content, ref LTag, ref fields, ref isObjects));
                }
                else
                {
                    bHasChildBlock = true;
                    ChildBlockIdxs.Add(i);
                    // Append declaration of new Block
                    BlockChunk block = (BlockChunk)(obj);
                    builder.Append(DeclareBlockVariable(block.Name, parentName, ref fields, ref isObjects));
                }
            }

            // Render ToString method
            builder.Append(RenderToStringMethod(ref LTag, fields, isObjects, (parentName == TemplateName)));

            // Close
            if (parentName == TemplateName)
            {
                builder.Append(CloseTemplate());
            }
            else
            {
                builder.Append(CloseBlock());
            }

            // Render next child Block
            if (bHasChildBlock)
            {
                c = ChildBlockIdxs.Count;
                for (int i = 0; i < c; i++)
                {
                    object obj = objs[ChildBlockIdxs[i]];
                    BlockChunk block = (BlockChunk)(obj);
                    List<string> lTag = new List<string>();

                    List<string> fs = new List<string>();
                    List<bool?> ios = new List<bool?>();

                    builder.Append(RenderBlock(block.Content, parentName + TplSettings.Seperator + block.Name, ref lTag));
                }
            }

            return builder.ToString();
        }

        // Non-block is contain tag and String, no child Block
        private string RenderNonBlock(string text, ref List<string> LTag, ref List<string> fields, ref List<bool?> isObjects)
        {
            if (String.IsNullOrEmpty(text)) return null;

            StringBuilder builder = new StringBuilder(1000);

            object[] bs = FindFirstTag(text);
            if (null == bs)
            {
                builder.Append(RenderString(text, ref fields, ref isObjects)); // Wow! Great!
            }
            else
            { // No problem, recursive loop it

                // Render String
                builder.Append(RenderString((string)(bs[0]), ref fields, ref isObjects));

                // Render tag
                builder.Append(RenderTag((string)(bs[1]), ref LTag, ref fields, ref isObjects));

                // Render non-block child
                builder.Append(RenderNonBlock((string)(bs[2]), ref LTag, ref fields, ref isObjects));
            }

            return builder.ToString();
        }

        private string DeclareBlockVariable(string name, ref List<string> fields, ref List<bool?> isObjects)
        {
            if (BlockVariables.ContainsKey(name))
            {
                int i = (int)(BlockVariables[name]) + 1;
                BlockVariables[name] = i;

                fields.Add(BlockVariablePrefix + name + i);
                isObjects.Add(true);

                return "\t\t\tpublic " + name + i + TplSettings.BlocSuffix + " " + fields[fields.Count - 1] + " = new " + name + i + TplSettings.BlocSuffix + "();\r\n";
            }
            else
            {
                BlockVariables.Add(name, 0);

                fields.Add(BlockVariablePrefix + name);
                isObjects.Add(true);

                return "\t\t\tpublic " + name + TplSettings.BlocSuffix + " " + fields[fields.Count - 1] + " = new " + name + TplSettings.BlocSuffix + "();\r\n";
            }
        }

        private string DeclareBlockVariable(string name, string parentName, ref List<string> fields, ref List<bool?> isObjects)
        {
            string p = parentName + TplSettings.Seperator + name;

            if (BlockVariables.ContainsKey(p))
            {
                int i = (int)(BlockVariables[p]) + 1;
                BlockVariables[p] = i;

                fields.Add(BlockVariablePrefix + name + i);
                isObjects.Add(true);

                return "\t\t\tpublic " + p + i + TplSettings.BlocSuffix + " " + fields[fields.Count - 1] + " = new " + p + i + TplSettings.BlocSuffix + "();\r\n";
            }
            else
            {
                BlockVariables.Add(p, 0);

                fields.Add(BlockVariablePrefix + name);
                isObjects.Add(true);

                return "\t\t\tpublic " + p + TplSettings.BlocSuffix + " " + fields[fields.Count - 1] + " = new " + p + TplSettings.BlocSuffix + "();\r\n";
            }
        }


        #endregion

        private string RenderTag(string name, ref List<string> LTag, ref List<string> fields, ref List<bool?> isObjects)
        {
            if (LTag.Contains(ToPropertyName(name)))
            { // Render reference to existed tag

                fields.Add(TagVariablePrefix + TagCounter++ + TplSettings.Seperator + ToPropertyName(name));
                isObjects.Add(null);

                return "\t\t\tprotected string " + fields[fields.Count - 1] + ";\r\n";
            }
            else
            {// Add and render new tag

                if (name.Contains(StaticStringPrefix)) // Static tag
                {
                    fields.Add(StringVariablePrefix + StringCounter++);
                    isObjects.Add(false);
                    LTag.Add(fields[fields.Count - 1]);

                    return "\t\t\tprotected static string " + fields[fields.Count - 1] + "{get{return " + name.Remove(0, StaticStringPrefix.Length) + ";}}\r\n";
                }
                else if (name.Contains(LoadStringPrefix))//{load:IBC.Agent.UI.Template1 template1 = new IBC.Agent.UI.Template1()}
                {
                    string var = string.Empty;
                    string declaration = RenderChild(name, ref var);

                    fields.Add(var);
                    isObjects.Add(false);
                    LTag.Add(fields[fields.Count - 1]);

                    return declaration;
                }
                else if (name.Contains(DefaultValueIndicator))
                {
                    string[] args = name.Split(new string[] { DefaultValueIndicator }, StringSplitOptions.None);

                    string defaultValue = args[1];
                    name = ToPropertyName(args[0]);

                    fields.Add(name);
                    isObjects.Add(false);
                    LTag.Add(name);

                    return "\t\t\tpublic string " + fields[fields.Count - 1] + " = \"" + defaultValue + "\";\r\n";

                }
                else
                {
                    name = ToPropertyName(name);

                    fields.Add(name);
                    isObjects.Add(false);
                    LTag.Add(name);

                    return "\t\t\tpublic string " + fields[fields.Count - 1] + " = \"{" + name + "}\";\r\n";
                }
            }
        }

        private string RenderString(string text, ref List<string> fields, ref List<bool?> isObjects)
        {
            // Remove all double white spaces
            text = Regex.Replace(text, "\\s{2,}", string.Empty);
            if (string.IsNullOrEmpty(text)) return null;

            fields.Add(StringVariablePrefix + StringCounter++);
            isObjects.Add(false);

            return "\t\t\tprotected static string " + fields[fields.Count - 1] + " = \"" + text.Replace("\"", "\\\"") + "\";\r\n";
        }

        #region Child Template

        /// <summary>
        /// Render a child and return it's name.
        /// </summary>
        /// <param name="command"></param>
        /// <returns></returns>
        private string RenderChild(string command, ref string name)
        {
            command = command.Remove(0, LoadStringPrefix.Length);
            int i1 = command.IndexOf(' ');
            int i2 = command.IndexOf('=');

            if (i1 == -1 || i2 == -1) return null;

            name = command.Substring(i1, i2 - i1).Trim();

            string privateName = "_" + name;
            string type = command.Substring(0, i1);
            string initial = command.Substring(i2 + 1);

            string publicMethod = "\t\t\tpublic " + type + " " + name + "{get {return " + privateName + " != null ? " + privateName + " : " + privateName + " = " + initial + ";}}\r\n";
            string privateDeclare = "\t\t\tprotected " + type + " " + privateName + ";\r\n";

            return publicMethod + privateDeclare;
        }

        #endregion

        #region ToString method

        private string OpenToString1Method()
        {
            return "\t\t\tpublic string ToString()\r\n\t\t\t{\r\n";
        }

        private string CloseToStringMethod()
        {
            return "\t\t\t}\r\n";
        }

        private string OpenToStringMethod()
        {
            return "\t\t\tpublic override void ToString(ref StringBuilder bd)\r\n\t\t\t{\r\n";
        }

        private string RenderToStringMethod(ref List<string> LTag, List<string> fields, List<bool?> isObjects, bool isTemplateClass) // ToString with StringBuilder param
        {
            StringBuilder bd = new StringBuilder(500);
            int c = 0;
            if (null == fields || ((c = fields.Count) == 0))
            {
                bd.Append(OpenToStringMethod());

                bd.Append("\t\t\t\tif(IsAssigned){bd.Append(Value);}\r\n");

                bd.Append(CloseToStringMethod());

                if (isTemplateClass)
                    bd.Append(RenderToString1Method());

                return bd.ToString();
            }

            bd.Append(OpenToStringMethod());
            string tab = "\t\t\t\t";

            bd.Append("\t\t\t\tif(!Visible) return;\r\n");


            bd.Append("\t\t\t\tif(RenderChild)\r\n\t\t\t\t{\r\n");
            tab = "\t\t\t\t\t";

            for (int i = 0; i < c; i++)
            {
                if (isObjects[i] == true)
                {
                    bd.Append(tab + "if(null != " + fields[i] + ") " + fields[i] + ".ToString(ref bd);\r\n");
                }
                else
                {
                    string name = fields[i];
                    int j = name.IndexOf(TplSettings.Seperator);
                    if (isObjects[i] == null && (-1 != j) && (LTag.Contains(name = name.Remove(0, j + TplSettings.Seperator.Length))))
                        bd.Append(tab + "bd.Append(" + name + ");\r\n");
                    else
                        bd.Append(tab + "bd.Append(" + fields[i] + ");\r\n");
                }
            }



            bd.Append("\t\t\t\t}\r\n");
            bd.Append("\t\t\t\tif(IsAssigned){bd.Append(Value);}\r\n");

            bd.Append(CloseToStringMethod());

            if (isTemplateClass)
                bd.Append(RenderToString1Method());

            return bd.ToString();
        }

        private string RenderToString1Method() // ToString with no param
        {
            StringBuilder bd = new StringBuilder(100);
            bd.Append(OpenToString1Method());

            bd.Append("\t\t\t\tStringBuilder bd = new StringBuilder();\r\n");

            bd.Append("\t\t\t\tToString(ref bd);\r\n");

            bd.Append("\t\t\t\treturn bd.ToString();\r\n");
            bd.Append(CloseToStringMethod());

            return bd.ToString();
        }


        #endregion

        #region Concatenation

        private string ToPropertyName(string name)
        {
            return name.Replace('-', '_'); // !!! Note: Do not make the length changed
        }

        private string ToNamespaceName(string name)
        {
            return name.Replace('-', '_').Replace('.', '_').Replace(' ', '_');
            // !!! Note: Do not make the length changed
        }

        #endregion

        #region Validation

        private bool IsBlockName(string name)
        {
            return Regex.IsMatch(name, "^[A-Za-z0-9_\\-]+$");
        }

        private bool IsTagName(string name)
        {
            return Regex.IsMatch(name, "^[^\r\n\t]+$");
        }

        #endregion
    }

    #region DataElement

    struct NonBlockChunk
    {
        public string Content;
        public NonBlockChunk(string content)
        {
            Content = content;
        }
    }

    struct BlockChunk
    {
        public string Name;
        public string Content;

        public BlockChunk(string name, string content)
        {
            Name = name;
            Content = content;
        }
    }

